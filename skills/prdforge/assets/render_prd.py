def rgb_forms(hex_):
    r, g_, b = (int(hex_[i:i + 2], 16) for i in (1, 3, 5))
    return [f"rgb({r}, {g_}, {b})", f"rgb({r},{g_},{b})"]


def clean_svg(svg):
    """Model-supplied SVG is data: drop scripts, event handlers and external references."""
    svg = re.sub(r"<script[\s\S]*?</script\s*>", "", svg, flags=re.I)
    svg = re.sub(r"\son[a-z]+\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)", "", svg, flags=re.I)
    svg = re.sub(r"\s(?:xlink:)?href\s*=\s*[\"']\s*(?:https?:|javascript:|//)[^\"']*[\"']", "", svg, flags=re.I)
    return re.sub(r"@import[^;]*;", "", svg, flags=re.I)


def bake_mermaid(src, n):
    """Mermaid source to themed inline SVG, or None when mmdc is missing or fails."""
    if not shutil.which("mmdc"):
        return None
    with tempfile.TemporaryDirectory() as tmp:
        mmd, cfg, out = os.path.join(tmp, "f.mmd"), os.path.join(tmp, "c.json"), os.path.join(tmp, "f.svg")
        with open(mmd, "w", encoding="utf-8") as f:
            f.write(src)
        with open(cfg, "w", encoding="utf-8") as f:
            json.dump(FIG_CFG, f)
        r = subprocess.run(["mmdc", "-i", mmd, "-o", out, "-b", "transparent", "-c", cfg],
                           capture_output=True, text=True, timeout=120)
        if r.returncode != 0 or not os.path.exists(out):
            return None
        with open(out, encoding="utf-8") as f:
            svg = f.read()
    svg = svg.replace("my-svg", f"prdfig{n}").replace(".edgeLabel rect{opacity:0.5;", ".edgeLabel rect{opacity:1;")
    for sentinel, token in FIG_TOKENS.items():
        if sentinel.startswith("#"):
            for form in rgb_forms(sentinel):
                svg = svg.replace(form, token)
        svg = svg.replace(sentinel, token)
    # edge gradients mermaid derives from a sentinel by hue arithmetic
    svg = re.sub(r'stop-color="hsla?\([^)]*\)"', f'stop-color="{dg("node-line")}"', svg)
    probe = re.sub(r"\.mermaidTooltip\{[^}]*\}", "", svg)  # tooltip box, never shown
    for inert in FIG_INERT:
        probe = probe.replace(inert, "")
    leaked = sorted(set(re.findall(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)|\b(?:white|black)\b", probe)))
    if leaked:
        BAKE_FAILED.append(f"diagram {n}: unthemed colour(s) {leaked[:6]}; pin the mermaid theme variable in FIG_CFG")
    return svg


def size_svg(svg, label):
    """Natural width as max-width, and never narrower than 620px (or its natural width
    when smaller) so a narrow screen scrolls the canvas instead of shrinking the text."""
    m = re.search(r"<svg\b[^>]*>", svg)
    if not m:
        return None
    tag = m.group(0)
    w = re.search(r'viewBox="[\d.\-]+[ ,]+[\d.\-]+[ ,]+([\d.]+)', tag) or re.search(r'max-width:\s*([\d.]+)px', tag) \
        or re.search(r'\swidth="([\d.]+)(?:px)?"', tag)
    nat = float(w.group(1)) if w else 620.0
    new = re.sub(r'\s(?:style|width|height|role|aria-label)="[^"]*"', "", tag)
    new = new[:-1].rstrip("/").rstrip() + (f' role="img" aria-label="{E(label)}" style="width:100%;height:auto;'
                                          f'max-width:{nat:.0f}px;min-width:{min(620, round(nat))}px">')
    if tag.endswith("/>"):
        new = new[:-1] + "/>"
    return svg.replace(tag, new, 1)


