LOAD_ATTRS = {"src", "srcset", "poster", "action", "formaction", "data", "background"}
HREF_LOADS = {"link", "use", "image", "feimage", "script"}  # tags whose href fetches something
EXT_URL = re.compile(r"\s*(?:https?:)?//", re.I)
CSS_EXT = (re.compile(r'@import\s+(?:url\()?\s*["\']?(?:https?:)?//[^\s"\')]{1,80}', re.I),
           re.compile(r'url\(\s*["\']?(?:https?:)?//[^\s"\')]{1,80}', re.I))


def external_refs(h):
    """External things the page would LOAD: src/srcset/poster/action-style attributes,
    href only on tags that fetch (link, svg use/image), and @import or url() in CSS.
    Anchor hrefs are navigation, not loads, and text content (escaped, so never a tag)
    is ignored, as are script bodies."""
    found, css = [], re.findall(r"<style\b[^>]*>([\s\S]*?)</style\s*>", h, re.I)
    tags = re.sub(r"(<(script|style|textarea)\b[^>]*>)[\s\S]*?(</\2\s*>)", r"\1\3", h, flags=re.I)
    for m in re.finditer(r"<([a-zA-Z][\w:-]*)\b([^>]*)>", tags):
        tag = m.group(1).lower()
        for am in re.finditer(r'([\w:-]+)\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s>]+))', m.group(2)):
            name = am.group(1).lower()
            val = html.unescape(am.group(2) or am.group(3) or am.group(4) or "")
            if name == "style":
                css.append(val)
            elif name in LOAD_ATTRS or (name in ("href", "xlink:href") and tag in HREF_LOADS):
                vals = [v.split()[0] for v in val.split(",") if v.strip()] if name == "srcset" else [val]
                found += [f"<{tag} {name}={v.strip()[:80]}>" for v in vals if EXT_URL.match(v)]
    for block in css:
        for rx in CSS_EXT:
            found += rx.findall(block)
    return found


def normalise_dashes(x):
    """Model text must not carry em or en dashes (the page check rejects them). A dash
    between numbers becomes a hyphen; any other one becomes a comma. Returns (value, count)."""
    if isinstance(x, str):
        n = x.count("\u2014") + x.count("\u2013")
        if not n:
            return x, 0
        t = re.sub(r"(?<=\d)\s*[\u2013\u2014]\s*(?=\d)", "-", x)
        t = re.sub(r"^\s*[\u2013\u2014]\s*", "", t)
        t = re.sub(r"\s*[\u2013\u2014]\s*$", "", t)
        t = re.sub(r"(?<=\w)[\u2013](?=\w)", "-", t)
        t = re.sub(r"\s*[\u2013\u2014]+\s*", ", ", t)
        return re.sub(r",\s*,", ",", t), n
    if isinstance(x, list):
        out, n = [], 0
        for v in x:
            v2, k = normalise_dashes(v)
            out.append(v2)
            n += k
        return out, n
    if isinstance(x, dict):
        out, n = {}, 0
        for k, v in x.items():
            v2, c = normalise_dashes(v)
            out[k] = v2
            n += c
        return out, n
    return x, 0


def check_html(h):
    problems = []
    if "{{" in h:
        problems.append("leftover {{ token")
    ext = external_refs(h)
    if ext:
        problems.append("external resource reference " + ext[0])
    if "<script>" not in h or "<style>" not in h:
        problems.append("inline script or style missing")
    if 'id="oq-list"' not in h:
        problems.append("open-questions list missing")
    if "PRDFORGE:" in h:
        problems.append("unfilled PRDFORGE marker")
    for cp, name in ((0x2014, "em dash"), (0x2013, "en dash")):
        if chr(cp) in h:
            problems.append(name + " in page")
    return problems


def run_lint(score_py, md_path):
    try:
        out = subprocess.run([sys.executable, score_py, md_path], capture_output=True, text=True, timeout=60).stdout
        j = json.loads(out.split("---JSON---", 1)[1].strip())
        return {"total": j.get("total"), "grade": j.get("grade"),
                "findings": [f["msg"] for f in j.get("findings", []) if f.get("level") in ("warn", "fail")]}
    except Exception as e:  # lint is advisory; never fail the render on it
        return {"total": None, "grade": None, "findings": [f"linter did not run: {e}"]}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True)
    ap.add_argument("--template", required=True)
    ap.add_argument("--lint", default=None)
    a = ap.parse_args()
    with open(a.json, encoding="utf-8") as f:
        p = json.load(f)
    p, dashes = normalise_dashes(p)
    if dashes:  # persist, so the markdown, prompt, bundle and any re-render all agree
        with open(a.json, "w", encoding="utf-8") as f:
            json.dump(p, f, indent=2, ensure_ascii=False)
    base = a.json[:-len("-prd.json")] if a.json.endswith("-prd.json") else os.path.splitext(a.json)[0]
    slug = os.path.basename(base)
    md_path, html_path, prompt_path = base + "-prd.md", base + "-prd.html", base + "-prompt.md"

    with open(prompt_path, "w", encoding="utf-8") as f:
        f.write(to_prompt(p))
    # lint first so the score can be shown inside the documents themselves
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(to_markdown(p))
    lint = run_lint(a.lint, md_path) if a.lint and os.path.exists(a.lint) else None
    if lint:
        p["lint"] = {"total": lint["total"], "grade": lint["grade"]}
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(to_markdown(p))
        with open(a.json, "w", encoding="utf-8") as f:
            json.dump(p, f, indent=2, ensure_ascii=False)
    with open(a.template, encoding="utf-8") as f:
        tpl = f.read()
    tpl = re.sub(r"<!--\s*prdforge-template-note[\s\S]*?-->\s*", "", tpl)
    nav, body, unplaced = to_html(p, slug)
    page = (tpl.replace("{{TITLE}}", E(g(p, "title")))
               .replace("<!--PRDFORGE:NAV-->", nav).replace("<!--PRDFORGE:BODY-->", body))
    with open(html_path, "w", encoding="utf-8") as f:
        f.write(page)
