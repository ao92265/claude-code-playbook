# ---------------------------------------------------------------- html (project-f style)
def table(headers, rows):
    h = "".join(f"<th>{E(x)}</th>" for x in headers)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tbl"><table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table></div>'


def lvl(level):
    lv = str(level or "").lower()
    cls = "high" if lv == "high" else "medium" if lv in ("medium", "med") else "low"
    return f'<span class="lvl {cls}">{E(lv or "n/a")}</span>'


def pill(text, cls="all"):
    return f' <span class="ws {cls}">{E(str(text))}</span>' if text else ""


def idd(v):
    """An ID where it is defined: the anchor every cross-reference jumps to."""
    v = str(v or "")
    return f'<span class="idd" id="id-{E(v)}">{E(v)}</span>' if v else ""


def link_ids(html_, ids):
    """Turn every mention of a known ID in prose into a link to where it is defined.
    Only text between tags is touched; definitions, links, code, pre and headings are skipped."""
    if not ids:
        return html_
    rx = re.compile(r"(?<![\w-])(" + "|".join(re.escape(i) for i in sorted(ids, key=len, reverse=True)) + r")(?![\w-])")
    out, skip = [], []
    for part in re.split(r"(<[^>]+>)", html_):
        if part.startswith("<"):
            m = re.match(r"<(/?)([a-zA-Z0-9]+)", part)
            if m:
                closing, tag = m.group(1) == "/", m.group(2).lower()
                opens_skip = tag in ("a", "code", "pre", "h1", "h2", "h3") or 'class="idd"' in part
                if not closing and opens_skip:
                    skip.append(tag)
                elif closing and skip and skip[-1] == tag:
                    skip.pop()
            out.append(part)
        elif skip:
            out.append(part)
        else:
            out.append(rx.sub(lambda m: f'<a class="idref" href="#id-{m.group(1)}">{m.group(1)}</a>', part))
    return "".join(out)


def heatmap(risks):
    order = ["low", "medium", "high"]
    cells = {(i, l): [] for i in order for l in order}
    for x in risks:
        i, l = str(g(x, "impact")).lower(), str(g(x, "likelihood")).lower()
        if (i, l) in cells:
            cells[(i, l)].append(str(g(x, "id")))
    rows = []
    for i in reversed(order):
        tds = "".join(f'<td class="hm s{order.index(i) + order.index(l)}">' +
                      " ".join(f'<a class="idref" href="#id-{E(r)}">{E(r)}</a>' for r in cells[(i, l)]) + "</td>" for l in order)
        rows.append(f'<tr><th scope="row">{i}</th>{tds}</tr>')
    return ('<div class="heat"><table><thead><tr><th>Impact / likelihood</th>' +
            "".join(f"<th>{l}</th>" for l in order) + "</tr></thead><tbody>" + "".join(rows) + "</tbody></table></div>")


