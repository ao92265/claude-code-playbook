def check_diagrams(p, page_html=None):
    """Diagrams are mandatory: at least 3, covering the system, the main flow and the delivery.
    With page_html (the rendered PRD), also fail when any figure is raw mermaid source
    instead of baked SVG, which is what a render without mmdc produces."""
    ds = [x for x in (g(p, "diagrams", []) or []) if isinstance(x, dict)]
    problems = []
    if page_html is not None and '<pre class="mermaid">' in page_html:
        problems.append("diagrams: figure(s) shown as raw mermaid source, not SVG; "
                        "re-render with mmdc on PATH (npm i -g @mermaid-js/mermaid-cli)")
    if len(ds) < 3:
        problems.append(f"diagrams: {len(ds)} found, at least 3 required (system, flow, delivery)")
    kinds = {str(g(x, "kind")).lower() for x in ds}
    missing = [k for k in REQUIRED_KINDS if k not in kinds]
    if ds and missing:
        problems.append("diagrams: missing kind " + ", ".join(missing))
    for i, x in enumerate(ds, 1):
        if not (g(x, "mermaid") or g(x, "svg")):
            problems.append(f"diagram {i} has no mermaid or svg source")
        if not g(x, "caption"):
            problems.append(f"diagram {i} has no caption")
    return problems


def figure(x, n):
    label = str(g(x, "label") or g(x, "caption") or f"Figure {n}")
    svg = clean_svg(str(g(x, "svg"))) if g(x, "svg") else bake_mermaid(str(g(x, "mermaid")), n) if g(x, "mermaid") else None
    if g(x, "mermaid") and not g(x, "svg") and svg is None:
        if not shutil.which("mmdc"):
            if MMDC_MISSING not in BAKE_FAILED:
                BAKE_FAILED.append(MMDC_MISSING)
        else:
            BAKE_FAILED.append(f"diagram {n} ({label}): mermaid did not render; fix its syntax")
    svg = size_svg(svg, label) if svg else None
    cap = g(x, "caption")
    capt = f'<figcaption><b>Figure {n}.</b> {E(str(cap))}</figcaption>' if cap else ""
    if not svg:  # keep the source readable for a human, but BAKE_FAILED already fails the check
        return f'<figure class="fig"><pre class="mermaid">{E(str(g(x, "mermaid")))}</pre>{capt}</figure>' if g(x, "mermaid") else ""
    return (f'<figure class="fig"><div class="fig-canvas" tabindex="0" role="region" aria-label="{E(label)}, scrolls sideways">'
            f'{svg}</div>{capt}</figure>')


class Doc:
    """Collects chapters and the sidebar nav in step, so the two can never drift."""
    def __init__(self, diagrams=None):
        self.body, self.nav, self.no, self.figs = [], [], 0, 0
        self.diagrams = [x for x in (diagrams or []) if isinstance(x, dict)]

    def group(self, name):
        self.nav.append(f'<div class="nav-group">{E(name)}</div>')
        self.act = name

    def chapter(self, anchor, title, html_):
        self.no += 1
        self.nav.append(f'<ul><li><a href="#{anchor}">{self.no} · {E(title)}</a></li></ul>')
        self.body.append(f'<a id="{anchor}"></a><h2><span class="ch-kicker"><span class="ch-act">{E(self.act)}</span>'
                         f'<span class="ch-no">Chapter {self.no}</span></span><span class="ch-title">{E(title)}</span></h2>\n{html_}'
                         + self.figures_for(anchor))

    def figures_for(self, anchor):
        out = []
        for x in self.diagrams:
            if str(g(x, "chapter") or KIND_CHAPTER.get(str(g(x, "kind")).lower(), "")) == anchor:
                self.figs += 1
                out.append(figure(x, self.figs))
        return "".join(out)


