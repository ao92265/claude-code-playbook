#!/usr/bin/env python3
"""Deterministic PRD renderer for prdforge.

Reads <outDir>/<slug>-prd.json (the PRD model the workflow produced) and writes:
  <slug>-prd.html   self-contained interactive PRD (template shell + rendered body)
  <slug>-prd.md     the same content as markdown, the input for the prd-review linter
  <slug>-prompt.md  the implementation prompt (Context / Objective / Boundaries / Validation)

Then self-checks the HTML (no leftover tokens, no external refs, inline script and style
intact, every diagram baked to SVG) and, when --lint points at prd-review's score.py, scores
the markdown. Em and en dashes in the model's text are normalised before rendering (and the
JSON rewritten), so one stray dash does not fail the page. Diagrams need mmdc on PATH
(npm i -g @mermaid-js/mermaid-cli); without it the render fails rather than ship raw source.

Usage:
  render_prd.py --json <path> --template <prd-template.html> [--lint <score.py>]
Prints one JSON line on stdout: {htmlPath, mdPath, promptPath, checks, lint}.
Exit 1 if a self-check fails.

Rendering lives here, not in an LLM prompt, so the same model always produces the same page.
"""
import argparse, html, json, os, re, shutil, subprocess, sys, tempfile

E = html.escape


def g(d, k, default=""):
    v = d.get(k, default) if isinstance(d, dict) else default
    return default if v is None else v


def ids_join(xs):
    return ", ".join(str(x) for x in (xs or []))


